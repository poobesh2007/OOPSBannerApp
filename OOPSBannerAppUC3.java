/**
 * OOPS Banner App - UC3
 * Purpose: Display "OOPS" using String.join() for better memory efficiency.
 * @author poobesh
 * @version 3.0
 */
public class OOPSBannerAppUC3 {
    public static void main(String[] args) {

        System.out.println(String.join(" ",
                "*****", "*****", "*****", "*****"));

        System.out.println(String.join(" ",
                "*   *", "*   *", "*   *", "*"));

        System.out.println(String.join(" ",
                "*   *", "*   *", "*   *", "*"));

        System.out.println(String.join(" ",
                "*   *", "*   *", "*****", "*****"));

        System.out.println(String.join(" ",
                "*   *", "*   *", "*", "*   *"));

        System.out.println(String.join(" ",
                "*   *", "*   *", "*", "*   *"));

        System.out.println(String.join(" ",
                "*****", "*****", "*", "*****"));
    }
}